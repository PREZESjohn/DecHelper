let documents= [];
let currentPage = 0;
let pageSize = 5;
let totalPages = 1;

document.getElementById('document-form').addEventListener('submit', async function(e) {
    e.preventDefault();
    const id = document.getElementById('doc-id').value;
    const text = document.getElementById('doc-text').value;
    let metadata;
    try {
        metadata = JSON.parse(document.getElementById('doc-metadata').value || '{}');
    } catch (err) {
        alert('Invalid JSON in metadata');
        return;
    }

    const documentTmp = { id, text, metadata };
    try {
        if (id) {
            // Update existing document
            await fetch(`http://localhost:8000/api/v1/docs/update`, {
                method: 'PUT',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify(documentTmp)
            });
        } else {
            // Create new document
            await fetch(`http://localhost:8000/api/v1/docs/add`, {
                method: 'PUT',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ text, metadata }) // ID is generated by backend
            });
        }
        document.getElementById('document-form').reset();
        document.getElementById('doc-id').value = '';
        await fetchDocuments();
    } catch (err) {
        console.error('Error saving document:', err);
        alert('Failed to save document');
    }
});

document.getElementById('clear-form').addEventListener('click', function() {
    document.getElementById('document-form').reset();
    document.getElementById('doc-id').value = '';
});

document.getElementById('prev-page').addEventListener('click', function() {
    if (currentPage > 0) {
        currentPage--;
        fetchDocuments();
    }
});

document.getElementById('next-page').addEventListener('click', function() {
    if (currentPage < totalPages - 1) {
        currentPage++;
        fetchDocuments();
    }
});

document.getElementById('page-size').addEventListener('change', function(e) {
    pageSize = parseInt(e.target.value);
    currentPage = 0; // Reset to first page
    fetchDocuments();
});

async function fetchDocuments() {
    try {
        const response = await fetch(`http://localhost:8000/api/v1/docs/all-page/page=${currentPage},offset=${pageSize}`);
        const data = await response.json();
        documents = data.content;
        totalPages = data.totalPages;
        updatePaginationControls();
        renderDocuments();
    } catch (err) {
        console.error('Error fetching documents:', err);
        alert('Failed to fetch documents');
    }
}

function updatePaginationControls() {
    document.getElementById('page-info').textContent = `Page ${currentPage + 1} of ${totalPages}`;
    document.getElementById('prev-page').disabled = currentPage === 0;
    document.getElementById('next-page').disabled = currentPage >= totalPages - 1;
    document.getElementById('page-size').value = pageSize;
}

function renderDocuments() {
    const tableBody = document.getElementById('document-table');
    tableBody.innerHTML = '';
    documents.forEach(doc => {
        const row = document.createElement('tr');
        row.innerHTML = `
            <td class="px-6 py-4 whitespace-nowrap">${doc.id}</td>
            <td class="px-6 py-4">${doc.text.substring(0, 50)}${doc.text.length > 50 ? '...' : ''}</td>
            <td class="px-6 py-4">${JSON.stringify(doc.metadata)}</td>
            <td class="px-6 py-4 whitespace-nowrap">
                <button onclick="editDocument('${doc.id}')" class="text-blue-500 hover:underline mr-2">Edit</button>
                <button onclick="deleteDocument('${doc.id}')" class="text-red-500 hover:underline">Delete</button>
            </td>
        `;
        tableBody.appendChild(row);
    });
}

function editDocument(id) {
    const doc = documents.find(doc => doc.id === id);
    if (doc) {
        document.getElementById('doc-id').value = doc.id;
        document.getElementById('doc-text').value = doc.text;
        document.getElementById('doc-metadata').value = JSON.stringify(doc.metadata, null, 2);
    }
}

async function deleteDocument(id) {
    if (confirm('Are you sure you want to delete this document?')) {
        try {
            await fetch(`http://localhost:8000/api/v1/docs/delete-id/${id}`, {
                method: 'DELETE'
            });
            fetchDocuments();
        } catch (err) {
            console.error('Error deleting document:', err);
            alert('Failed to delete document');
        }
    }
}

fetchDocuments();